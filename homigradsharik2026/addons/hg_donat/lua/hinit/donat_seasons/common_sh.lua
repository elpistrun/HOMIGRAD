function PAGE.Open(frame,banner)
    local drawParticles = donatPanel.Create3DParticles(banner,randomModels)

    function banner:Draw(w,h)
        render.SetColorModulation(1,1,1)--WTF, где-то лик блядь чтоле?

        //PAGE.Draw(w,h)
        drawParticles(self,w,h)

        local x,y = self:LocalToScreen(0,0)

        DrawBlur(3,x,y)

        cam.Start3D(Vector(0,500,0),(-Vector(0,100,0)):Angle(),12,x,y,w,h)
            local mdl = CSM.GetByID("models/kali/props/cases/hard case c.mdl",tostring(self) .. "main")
            mdl:SetNoDraw(true)
            mdl:SetPos(Vector(0.5,200 + self.hovered * 5,-6))
            mdl:SetAngles(Angle(20,110,0))
            mdl:DrawModel()
        cam.End3D()
    end

    donatPanel:CreatePanelShop(frame,{1,2,3,4})
end