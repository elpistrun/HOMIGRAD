local filter

if SERVER then
    filter = function(ent)
        if ent:IsRagdoll() or ent:IsPlayer() or ent:IsNPC() then return false end

        return true
    end
else
    filter = function(ent)
        if ent:IsRagdoll() or ent:IsPlayer() or ent:IsNPC() or ent == GetViewEntity() then return false end

        return true
    end
end

local tr = {
    mask = MASK_SHOT,
    filter = filter
}

function sound.GetPositionState(pos,filter)
    tr.start = pos
    tr.endpos = pos:Clone()
    tr.endpos[3] = tr.endpos[3] + SOUND_ROOF_DISTANCE
    
    local result = util.TraceLine(tr)

    return result.Hit and not result.HitSky and "indoors" or "outdoors"
end

if CLIENT then
    local delayCheck = 0

    event.Add("PreRender","sound.GetPositionState",function(ply,view)
        local time = RealTime()
        if delayCheck > time then return end
        delayCheck = time + 1 / 24
        
        SoundPositionState = sound.GetPositionState(RenderView.origin)
    end)

    local random = math.random

    local soundMetrsMax = 1000
    local soundMetrsCloseMax = 100

    net.Receive("sound.EmitGunShoot",function()
        sound.EmitGunShoot(net.ReadVector(),net.ReadString(),net.ReadString(),net.ReadFloat())
    end)
    
    function sound.EmitGunShoot(pos,id,ammoType,volume,dsp)
        local point
        
        if TypeID(pos) == TYPE_ENTITY then
            point = pos
            pos = point:GetPos()
        end
        
        local metrs = pos:Distance(RenderView.origin) * UNITS_TO_METERS

        dsp = dsp or 0

        volume = (volume or 1)

        local divDistance = 0.7

        local srcPositionState = sound.GetPositionState(pos)

        if srcPositionState == "indoors" then
            divDistance = 0.4

            if metrs > soundMetrsCloseMax * 2 then
                srcPositionState = "outdoors"
            end
        end

        if ammoType == "explosions" then divDistance = 0.8 end

        local volumeClose,volumeDistant = 1,1

        volumeClose = 1 - math.min(metrs / soundMetrsCloseMax,1)
        volumeDistant = 1 - math.min(metrs / soundMetrsMax,1)

        volumeDistant = Lerp(math.min(volumeClose * 3,1),volumeDistant,0)
        volumeDistant = math.min(volumeDistant * 1.5,1)
        
        volumeClose,volumeDistant = volumeClose * volume,volumeDistant * volume

        if volumeClose < 0.1 and volumeDistant < 0.1 then return end

        if not point then
            point = sound.GetVurtialEmit(pos,id,5)
            point.pos = pos
            point.Think = sound.ThinkGoAway
            point.panoramaEffect = 0.6
            point:Think()
        end

        local list = listIndex[ammoType]
        if not list then list = listIndex.pistol end

        if volumeClose > 0.1 then
            local sndClose = list[srcPositionState].close
            local sndNameClose = sndClose.list[random(1,#sndClose.list)]

            if sndClose.dontRepeat then
                if point.lastSND_GunShootReverb_Close then point:StopSound(point.lastSND_GunShootReverb_Close) end
                point.lastSND_GunShootReverb_Close = sndNameClose
            end

            point:EmitSound(sndNameClose,140,random(96,104) + (sndClose.pitch or 0),volumeClose * (sndClose.volume or 1),CHAN_STATIC,nil,dsp)

            local sndKick = list[srcPositionState].kick

            if sndKick then
                local sndNameKick = sndKick.list[random(1,#sndKick.list)]
                if point.lastSND_GunShootReverb_Kick then point:StopSound(point.lastSND_GunShootReverb_Kick) end
                point.lastSND_GunShootReverb_Kick = sndNameKick

                --point:EmitSound(sndNameKick,140,random(96,104) - (sndClose.pitch or 0),volumeClose * (sndKick.volume or 1),CHAN_STATIC,nil,dsp)
            end
        end

        if volumeDistant > 0.1 then
            local sndDistant = list[srcPositionState].distant
            local sndNameDistant = sndDistant.list[random(1,#sndDistant.list)]

            if sndDistant.dontRepeat then
                if point.lastSND_GunShootReverb_Distant then point:StopSound(point.lastSND_GunShootReverb_Distant) end
                point.lastSND_GunShootReverb_Distant = sndNameDistant
            end

            point:EmitSound(sndNameDistant,140,random(96,104) + (sndDistant.pitch or 0),volumeDistant * (sndDistant.volume or 1),CHAN_STATIC,nil,dsp)
        end
    end

